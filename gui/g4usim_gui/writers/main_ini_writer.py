from __future__ import annotations

from pathlib import Path

from g4usim_gui.editors.source_physics_scoring_model import (
    PhysicsEditableModel,
    ScoringEditableModel,
    SourceEditableModel,
    validate_physics_model,
    validate_scoring_model,
    validate_source_model,
)
from g4usim_gui.models.package_model import GeometrySettings, RunPackage
from g4usim_gui.models.physics_model import PhysicsSettings
from g4usim_gui.models.run_model import RunSettings
from g4usim_gui.models.scoring_model import ScoringSettings
from g4usim_gui.models.source_model import SourceSettings


def _bool(value: bool) -> str:
    return "true" if value else "false"


def write_main_ini(
    path: str | Path,
    *,
    package: RunPackage,
    run: RunSettings,
    geometry: GeometrySettings,
    source: SourceSettings,
    physics: PhysicsSettings,
    scoring: ScoringSettings,
    source_model: SourceEditableModel | None = None,
    physics_model: PhysicsEditableModel | None = None,
    scoring_model: ScoringEditableModel | None = None,
) -> None:
    """Write the standard G4UniversalSim main.ini used by SimulationManager."""
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    text = build_main_ini_text(
        package=package,
        run=run,
        geometry=geometry,
        source=source,
        physics=physics,
        scoring=scoring,
        source_model=source_model,
        physics_model=physics_model,
        scoring_model=scoring_model,
    )
    target.write_text(text, encoding="utf-8", newline="\n")


def build_main_ini_text(
    *,
    package: RunPackage,
    run: RunSettings,
    geometry: GeometrySettings,
    source: SourceSettings,
    physics: PhysicsSettings,
    scoring: ScoringSettings,
    source_model: SourceEditableModel | None = None,
    physics_model: PhysicsEditableModel | None = None,
    scoring_model: ScoringEditableModel | None = None,
) -> str:
    source_model = source_model or SourceEditableModel.from_settings(source)
    physics_model = physics_model or PhysicsEditableModel.from_settings(physics)
    scoring_model = scoring_model or ScoringEditableModel.from_settings(scoring)
    validate_source_model(source_model)
    validate_physics_model(physics_model)
    validate_scoring_model(scoring_model)
    errors = source_model.errors + physics_model.errors + scoring_model.errors
    if errors:
        raise ValueError("Cannot generate main.ini with editor validation errors:\n" + "\n".join(errors))

    seed_line = f"seed = {run.seed}\n" if run.seed is not None else ""
    return f"""# Generated by G4UniversalSim PySide6 Runner.

[run]
name = {run.run_name}
threads = {run.threads}
{seed_line}interactive = false
verbose = 1
check_overlaps = {_bool(run.check_overlaps)}
dry_run = {_bool(run.dry_run)}

[output]
dir = {package.output_dir}

[materials]
file = {package.materials_ini_path}

[geometry]
template = {geometry.template}
config = {package.geometry_ini_path}
check_overlaps = {_bool(run.check_overlaps)}
default_world_material = G4_AIR

[physics]
mode = reference
reference = {physics_model.reference_list}
default_cut = {physics_model.default_cut}
biasing = {_bool(physics_model.enable_biasing_physics)}
verbose = 1

[source]
preset = {source_model.preset}
particle = {source_model.particle}
energy = {source_model.energy}
position_type = {source_model.position_type}
position = {source_model.position}
direction = {source_model.direction}

[scoring]
enabled = {_bool(scoring_model.enabled)}
hits = {_bool(scoring_model.hits)}
event_edep = {_bool(scoring_model.event_edep)}
edep = {_bool(scoring_model.edep)}
let = false
dose = false
fluence = false
auto_create_default_scorers = {_bool(scoring_model.auto_create_default_scorers)}
verbose = {scoring_model.verbose}

[scoring.edep]
raw_histogram = {_bool(scoring_model.raw_histogram)}
weighted_histogram = {_bool(scoring_model.weighted_histogram)}
bins = {scoring_model.hist_bins}
min = {scoring_model.hist_min}
max = {scoring_model.hist_max}
volume_summary = {_bool(scoring_model.volume_summary)}
particle_summary = {_bool(scoring_model.particle_summary)}

[biasing]
enabled = false
"""
