from __future__ import annotations

from pathlib import Path

from g4usim_gui.editors.geometry_editor_model import (
    HIERARCHICAL_GEOMETRY_MODES,
    GeometryDocument,
    geometry_material_refs,
    validate_geometry_document,
)


def generate_geometry_ini_text(document: GeometryDocument) -> str:
    validate_geometry_document(document, material_names=geometry_material_refs(document))
    if document.errors:
        raise ValueError("Geometry Editor validation failed:\n" + "\n".join(document.errors))
    if document.mode == "simple_box":
        return _generate_simple_box(document)
    if document.mode == "layered_device":
        return _generate_layered_device(document)
    if document.mode in HIERARCHICAL_GEOMETRY_MODES:
        return _generate_hierarchical(document)
    raise ValueError(f"Geometry template '{document.mode}' is preview-only and cannot be generated by the GUI MVP.")


def write_geometry_ini(path: str, document: GeometryDocument) -> None:
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(generate_geometry_ini_text(document), encoding="utf-8", newline="\n")


def _generate_simple_box(document: GeometryDocument) -> str:
    model = document.simple_box
    lines = [
        "# Generated by G4UniversalSim GUI Geometry Editor.",
        "# Source geometry.ini is not overwritten.",
        "",
        "[world]",
        f"size = {model.world_size}",
        f"material = {model.world_material}",
        "",
        "[target]",
        f"name = {model.target_name}",
        "shape = box",
        f"size = {model.target_size}",
        f"material = {model.target_material}",
        f"position = {model.target_position}",
        f"rotation = {model.target_rotation}",
        f"sensitive = {_bool(model.target_sensitive)}",
        f"bias = {_bool(model.target_bias)}",
    ]
    if model.target_region.strip():
        lines.append(f"region = {model.target_region.strip()}")
    lines.extend(
        [
            "",
            "[visual.world]",
            "color = white",
            "alpha = 0.05",
            "visible = true",
            "wireframe = true",
            "",
            "[visual.target]",
            "color = blue",
            "alpha = 0.6",
            "visible = true",
            "wireframe = false",
            "",
        ]
    )
    return "\n".join(lines)


def _generate_layered_device(document: GeometryDocument) -> str:
    model = document.layered_device
    layers = [layer for layer in model.layers if layer.enabled]
    names = ", ".join(layer.name.strip() for layer in layers)
    lines = [
        "# Generated by G4UniversalSim GUI Geometry Editor.",
        "# Source geometry.ini is not overwritten.",
        "",
        "[world]",
        f"size = {model.world_size}",
        f"material = {model.world_material}",
        "",
        "[layers]",
        f"count = {len(layers)}",
        f"names = {names}",
        "auto_stack = true",
        "axis = z",
        f"gap = {model.gap}",
    ]
    if model.z_start.strip():
        lines.append(f"z_start = {model.z_start.strip()}")
    lines.append("")
    for layer in layers:
        lines.extend(
            [
                f"[layer.{layer.name.strip()}]",
                f"thickness = {layer.thickness.strip()}",
                f"xy = {layer.xy.strip()}",
                f"material = {layer.material.strip()}",
                f"sensitive = {_bool(layer.sensitive)}",
                f"bias = {_bool(layer.bias)}",
            ]
        )
        if layer.region.strip():
            lines.append(f"region = {layer.region.strip()}")
        if layer.copy_no.strip():
            lines.append(f"copyNo = {layer.copy_no.strip()}")
        lines.append("")
    return "\n".join(lines)


def _bool(value: bool) -> str:
    return "true" if value else "false"


def _generate_hierarchical(document: GeometryDocument) -> str:
    volumes = [volume for volume in document.volumes if volume.enabled]
    boolean_ops = [op for op in document.boolean_ops if op.enabled]
    lines = [
        "# Generated by G4UniversalSim GUI Hierarchical/Boolean Geometry Editor.",
        "# Source geometry.ini is not overwritten.",
        "# Boolean tools are solid operands, not ordinary volumes.",
        "",
    ]
    for volume in volumes:
        section = "[world]" if volume.name.strip().lower() == "world" else f"[volume.{volume.name.strip()}]"
        lines.append(section)
        if volume.name.strip().lower() != "world":
            lines.append(f"parent = {volume.parent.strip() or 'world'}")
        lines.append(f"shape = {volume.shape.strip() or 'box'}")
        shape = volume.shape.strip().lower()
        if shape == "box":
            lines.append(f"size = {volume.size.strip() or '1 mm,1 mm,1 mm'}")
        elif volume.size.strip():
            lines.append(f"size = {volume.size.strip()}")
        if volume.parameters.strip():
            lines.append(f"parameters = {volume.parameters.strip()}")
        lines.append(f"material = {volume.material.strip() or 'G4_AIR'}")
        if volume.position.strip():
            lines.append(f"position = {volume.position.strip()}")
        if volume.rotation.strip():
            lines.append(f"rotation = {volume.rotation.strip()}")
        if volume.sensitive:
            lines.append("sensitive = true")
        if volume.bias:
            lines.append("bias = true")
        if volume.region.strip():
            lines.append(f"region = {volume.region.strip()}")
        if volume.copy_no.strip():
            lines.append(f"copyNo = {volume.copy_no.strip()}")
        for item in _metadata_lines(volume.metadata):
            lines.append(item)
        lines.append("")

    by_target: dict[str, list] = {}
    for op in boolean_ops:
        by_target.setdefault(op.target_volume.strip(), []).append(op)
    for target, ops in by_target.items():
        for new_index, op in enumerate(ops):
            lines.append(f"[volume.{target}.boolean.{new_index}]")
            lines.append(f"operation = {op.operation.strip().lower() or 'subtraction'}")
            lines.append(f"shape = {op.tool_shape.strip().lower() or 'box'}")
            shape = op.tool_shape.strip().lower()
            if shape == "box":
                lines.append(f"size = {op.tool_size.strip() or '1 mm,1 mm,1 mm'}")
            elif op.tool_size.strip():
                lines.append(f"size = {op.tool_size.strip()}")
            if op.tool_parameters.strip():
                lines.append(f"parameters = {op.tool_parameters.strip()}")
            if op.position.strip():
                lines.append(f"position = {op.position.strip()}")
            if op.rotation.strip():
                lines.append(f"rotation = {op.rotation.strip()}")
            if op.name.strip():
                lines.append(f"name = {op.name.strip()}")
            lines.append("")
    return "\n".join(lines)


def _metadata_lines(metadata: str) -> list[str]:
    lines: list[str] = []
    for raw in metadata.splitlines():
        text = raw.strip()
        if not text or text.startswith("#") or "=" not in text:
            continue
        key, value = text.split("=", 1)
        key = key.strip()
        if key.lower() in {"material", "sensitive", "bias", "region", "parent", "shape", "size", "parameters", "position", "rotation", "copyno", "copy_no"}:
            continue
        lines.append(f"{key} = {value.strip()}")
    return lines
