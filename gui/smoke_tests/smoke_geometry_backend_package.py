ROOT = Path(__file__).resolve().parents[2]


@dataclass
class BackendResult:
    package_dir: Path
    exit_code: int | None
    stdout_path: Path | None
    stderr_path: Path | None
    skipped: bool = False


def _make_paths(tmp: Path, exe: Path) -> PathSettings:
    return PathSettings(
        executable=str(exe),
        workspace_root=str(ROOT),
        runs_root=str(tmp / "runs"),
        materials_config=str(ROOT / "config" / "materials" / "material.ini"),
        geometry_config=str(ROOT / "config" / "geometry" / "simple_box.ini"),
    )


def _dummy_exe(tmp: Path) -> Path:
    path = tmp / "G4UniversalSim.exe"
    path.write_text("", encoding="utf-8")
    return path


def _simple_document() -> GeometryDocument:
    doc = GeometryDocument(mode="simple_box", is_dirty=True)
    doc.simple_box.world_size = "10 cm, 10 cm, 10 cm"
    doc.simple_box.world_material = "G4_AIR"
    doc.simple_box.target_name = "Target"
    doc.simple_box.target_shape = "box"
    doc.simple_box.target_size = "10 mm, 10 mm, 1 mm"
    doc.simple_box.target_material = "G4_Si"
    doc.simple_box.target_position = "0 mm, 0 mm, 0 mm"
    doc.simple_box.target_rotation = "0 deg, 0 deg, 0 deg"
    doc.simple_box.target_sensitive = True
    doc.simple_box.target_bias = False
    doc.simple_box.target_region = "SV"
    return doc


def _layered_document() -> GeometryDocument:
    doc = GeometryDocument(mode="layered_device", is_dirty=True)
    doc.layered_device.world_size = "20 cm, 20 cm, 20 cm"
    doc.layered_device.world_material = "G4_AIR"
    doc.layered_device.axis = "z"
    doc.layered_device.gap = "0 um"
    doc.layered_device.layers = [
        LayerRow(name="Al", material="G4_Al", thickness="1 mm", xy="10 mm, 10 mm"),
        LayerRow(name="Oxide", material="G4_WATER", thickness="0.5 mm", xy="10 mm, 10 mm"),
        LayerRow(name="Si", material="G4_Si", thickness="0.3 mm", xy="10 mm, 10 mm", sensitive=True, region="SV"),
    ]
    return doc


def _source() -> SourceSettings:
    return SourceSettings(
        preset="proton_beam",
        particle="proton",
        energy="10 MeV",
        position="0 mm, 0 mm, -5 mm",
        direction="0,0,1",
    )


def _create_package(tmp: Path, name: str, template_name: str, doc: GeometryDocument, exe: Path) -> tuple[Path, str]:
    package, report = create_run_package(
        project=G4USimProject(projectName=name),
        paths=_make_paths(tmp, exe),
        run=RunSettings(run_name=name, threads=1, beam_on=100, check_overlaps=True),
        geometry=GeometrySettings(template=template_name, config_path=str(ROOT / "config" / "geometry" / "simple_box.ini")),
        source=_source(),
        physics=PhysicsSettings(reference="FTFP_BERT_EMZ", default_cut="1 mm", enable_biasing=False),
        scoring=ScoringSettings(enabled=True, hits=True, event_edep=True, edep=True, hist_bins=100, hist_min="0 eV", hist_max="10 MeV"),
        geometry_document=doc,
    )
    return Path(package.package_dir), report


def _assert_generated_package(package_dir: Path, template_name: str, expected_tokens: list[str]) -> None:
    geometry_path = package_dir / "config" / "geometry" / "geometry.ini"
    main_ini = package_dir / "config" / "main.ini"
    validation = package_dir / "validation_report.txt"
    assert geometry_path.is_file(), geometry_path
    assert main_ini.is_file(), main_ini
    assert validation.is_file(), validation
    geometry_text = geometry_path.read_text(encoding="utf-8")
    for token in expected_tokens:
        assert token in geometry_text, f"missing token in generated geometry.ini: {token}"
    main_text = main_ini.read_text(encoding="utf-8")
    assert f"template = {template_name}" in main_text
    assert f"config = {geometry_path}" in main_text
    report_text = validation.read_text(encoding="utf-8")
    assert "geometry_source_mode = generated by Geometry Editor" in report_text
    assert "materials_source_mode = copied from source" in report_text


def _run_backend(package_dir: Path, exe: Path, *, threads: int = 1, output_name: str = "output") -> BackendResult:
    output_dir = package_dir / output_name
    if output_dir.exists():
        shutil.rmtree(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    logs_dir = package_dir / "logs"
    logs_dir.mkdir(parents=True, exist_ok=True)
    stdout_path = logs_dir / f"backend_{output_name}_stdout.log"
    stderr_path = logs_dir / f"backend_{output_name}_stderr.log"
    command = [
        str(exe),
        "--config",
        str(package_dir / "config" / "main.ini"),
        "--macro",
        str(package_dir / "macros" / "run.mac"),
        "--output",
        str(output_dir),
        "--threads",
        str(threads),
    ]
    completed = subprocess.run(command, cwd=str(ROOT), text=True, capture_output=True, timeout=240, check=False)
    stdout_path.write_text(completed.stdout, encoding="utf-8", errors="replace")
    stderr_path.write_text(completed.stderr, encoding="utf-8", errors="replace")
    return BackendResult(package_dir=package_dir, exit_code=completed.returncode, stdout_path=stdout_path, stderr_path=stderr_path)


def _assert_backend_outputs(result: BackendResult, *, output_name: str = "output", threads: int = 1) -> bool:
    assert result.exit_code == 0, f"backend exit code={result.exit_code}, stderr={result.stderr_path.read_text(encoding='utf-8', errors='replace') if result.stderr_path else ''}"
    output_dir = result.package_dir / output_name
    stderr = result.stderr_path.read_text(encoding="utf-8", errors="replace") if result.stderr_path else ""
    assert "Fatal Exception" not in stderr
    assert "G4Exception" not in stderr or "JustWarning" in stderr
    assert "AIHLSDMT001" not in stderr
    assert (output_dir / "run_summary.txt").is_file()
    if threads == 1:
        assert (output_dir / "event_edep_t0.csv").is_file()
        assert (output_dir / "hist_edep_raw_t0.csv").is_file()
        assert (output_dir / "hist_edep_weighted_t0.csv").is_file()
        return True
    else:
        assert (output_dir / "event_edep_t0.csv").is_file()
        assert (output_dir / "hist_edep_raw_t0.csv").is_file()
        for index in range(threads):
            if not (output_dir / f"event_edep_t{index}.csv").is_file():
                print(
                    f"MT per-worker output not detected for t{index}; files={sorted(path.name for path in output_dir.glob('*'))}. "
                    "This backend may be a sequential Geant4 build or may not emit worker files in this environment."
                )
                return False
            if not (output_dir / f"hist_edep_raw_t{index}.csv").is_file():
                print(
                    f"MT raw histogram not detected for t{index}; files={sorted(path.name for path in output_dir.glob('*'))}. "
                    "This backend may be a sequential Geant4 build or may not emit worker files in this environment."
                )
                return False
        tasks = build_merge_plan(
            str(output_dir), str(ROOT), os.environ.get("G4USIM_MERGE_EXE", "")
        ).tasks
        assert any(task.kind == "event_edep" and task.available for task in tasks)
        assert any(task.kind == "hist_raw" and task.available for task in tasks)
        return True


def main() -> int:
    env_exe = os.environ.get("G4USIM_EXE", "").strip()
    with tempfile.TemporaryDirectory(prefix="g4usim_geometry_backend_") as tmp_raw:
        tmp = Path(tmp_raw)
        exe = Path(env_exe) if env_exe else _dummy_exe(tmp)
        simple_package, simple_report = _create_package(tmp, "simple_box_backend_smoke", "simple_box", _simple_document(), exe)
        layered_package, layered_report = _create_package(tmp, "layered_backend_smoke", "layered_device", _layered_document(), exe)
        hierarchical_source = ROOT / "test" / "geometry" / "hierarchical_test.ini"
        hierarchical_document = geometry_document_from_summary(parse_geometry(hierarchical_source, "hierarchical"), "hierarchical")
        assert not hierarchical_document.round_trip_blockers, hierarchical_document.round_trip_blockers
        hierarchical_document.is_dirty = True
        hierarchical_run, hierarchical_report = create_run_package(
            project=G4USimProject(projectName="hierarchical_backend_smoke"),
            paths=PathSettings(
                executable=str(exe), workspace_root=str(ROOT), runs_root=str(tmp / "runs"),
                materials_config=str(ROOT / "test" / "materials" / "test_materials.ini"),
                geometry_config=str(hierarchical_source),
            ),
            run=RunSettings(run_name="hierarchical_backend_smoke", threads=1, beam_on=3, check_overlaps=True),
            geometry=GeometrySettings(template="hierarchical", config_path=str(hierarchical_source)),
            source=_source(),
            physics=PhysicsSettings(reference="FTFP_BERT_EMZ", default_cut="1 mm", enable_biasing=False),
            scoring=ScoringSettings(enabled=True, hits=True, event_edep=True, edep=True, hist_bins=100, hist_min="0 eV", hist_max="10 MeV"),
            geometry_document=hierarchical_document,
        )
        hierarchical_package = Path(hierarchical_run.package_dir)

        _assert_generated_package(
            simple_package,
            "simple_box",
            ["[world]", "[target]", "size = 10 mm, 10 mm, 1 mm", "material = G4_Si", "sensitive = true"],
        )
        _assert_generated_package(
            layered_package,
            "layered_device",
            ["[layers]", "count = 3", "[layer.Al]", "material = G4_Al", "[layer.Si]", "sensitive = true"],
        )
        _assert_generated_package(
            hierarchical_package,
            "hierarchical",
            ["[volume.iron_stand]", "shape = trd", "dx1 = 8 cm", "dy2 = 10 cm", "dz = 2 cm", "cut.gamma = 0.5 mm", "vis.color = aqua"],
        )

        print(f"simple_box package: {simple_package}")
        print(f"layered_device package: {layered_package}")
        print("simple_box report contains generated geometry:", "geometry_source_mode = generated by Geometry Editor" in simple_report)
        print("layered_device report contains generated geometry:", "geometry_source_mode = generated by Geometry Editor" in layered_report)
        print("hierarchical report contains generated geometry:", "geometry_source_mode = generated by Geometry Editor" in hierarchical_report)

        if not env_exe:
            print("backend run skipped: set G4USIM_EXE to run C++ backend verification")
            return 0
        if not exe.is_file():
            raise FileNotFoundError(f"G4USIM_EXE does not exist: {exe}")

        simple_result = _run_backend(simple_package, exe, threads=1, output_name="output")
        _assert_backend_outputs(simple_result, output_name="output", threads=1)
        print("simple_box backend run: OK")

        layered_result = _run_backend(layered_package, exe, threads=1, output_name="output")
        _assert_backend_outputs(layered_result, output_name="output", threads=1)
        print("layered_device backend run: OK")

        hierarchical_result = _run_backend(hierarchical_package, exe, threads=1, output_name="output")
        _assert_backend_outputs(hierarchical_result, output_name="output", threads=1)
        hierarchical_summary = (hierarchical_package / "output" / "run_summary.txt").read_text(encoding="utf-8")
        assert "actual_completed_event_count = 3" in hierarchical_summary
        print("hierarchical backend run: OK")

        mt_result = _run_backend(simple_package, exe, threads=2, output_name="output")
        mt_ok = _assert_backend_outputs(mt_result, output_name="output", threads=2)
        print("simple_box backend MT run:", "OK" if mt_ok else "DEGRADED (single-worker output only)")

    print("smoke_geometry_backend_package: OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
