def check_backend_rules(root: Path) -> None:
    """Roadmap E1: the GUI reads and checks materials the way the backend's MaterialIniReader does."""
    from g4usim_gui.editors.geometry_editor_model import (   # noqa: PLC0415
        GeometryDocument, HierarchicalVolumeRow, validate_geometry_document)
    from g4usim_gui.parsers.materials_parser import material_reference_status   # noqa: PLC0415

    summary = parse_materials(root / "test" / "materials" / "test_materials.ini")
    names = {entry.name for entry in summary.materials}
    assert {"silicon", "iron", "water", "test_polymer"} <= names, names   # [material.X] defines X
    assert not any(name.lower().startswith(("element.", "isotope.", "material.")) for name in names), names
    assert any(text.startswith("[element.TestCarbon]") for text in summary.preserved_sections)
    document = material_document_from_summary(summary)
    assert not document.errors, document.errors
    polymer = next(row for row in document.rows if row.name == "test_polymer")
    assert [(c.name, c.value) for c in polymer.components] == [("TestCarbon", "2")]   # counts kept
    text = generate_materials_ini_text(document)
    assert "[element.TestCarbon]" in text and "[material.test_polymer]" in text and "material.material." not in text
    assert text.index("[element.TestCarbon]") < text.index("[material.test_polymer]")

    # names: custom ones case-insensitive, NIST ones exact (MaterialManager::GetMaterial)
    assert material_reference_status("SILICON", {"silicon"}) == "custom"
    assert material_reference_status("G4_WATER", set()) == "nist"
    assert material_reference_status("G4_lAr", set()) == "g4"
    assert material_reference_status("unobtainium", {"silicon"}) == "missing"

    # volume_fraction without density is auto; material loops are refused
    vf = MaterialDocument(rows=[MaterialRow(name="Mix", mode="volume_fraction", density="",
                                            components_text="G4_WATER:0.5, G4_Pb:0.5")])
    assert not validate_material_document(vf).errors, vf.errors
    loop = MaterialDocument(rows=[
        MaterialRow(name="A", mode="volume_fraction", density="auto", components_text="B:1"),
        MaterialRow(name="B", mode="volume_fraction", density="auto", components_text="A:1")])
    assert any("Circular material dependency: A -> B -> A" in e for e in validate_material_document(loop).errors)

    # geometry: lower-case reference to a capitalised material; a backend-only shape is an editor limit
    geometry = GeometryDocument(mode="hierarchical", volumes=[
        HierarchicalVolumeRow(name="world", shape="box", size="1 m, 1 m, 1 m", material="G4_AIR"),
        HierarchicalVolumeRow(name="Pad", parent="world", shape="box", size="1 cm, 1 cm, 1 cm", material="silicon",
                              position="0 mm, 0 mm, 0 mm", rotation="0 deg, 0 deg, 0 deg")])
    validate_geometry_document(geometry, material_names={"Silicon"})
    assert not geometry.errors, geometry.errors
    geometry.volumes[1].shape = "torus"
    validate_geometry_document(geometry, material_names={"Silicon"})
    assert any("supported by the backend but not by the Geometry Editor" in e for e in geometry.errors), geometry.errors
    geometry.source_copy_mode = True
    validate_geometry_document(geometry, material_names={"Silicon"})
    assert not any("not by the Geometry Editor" in e for e in geometry.errors), geometry.errors


def main() -> int:
    root = Path(__file__).resolve().parents[2]
    source_materials = root / "config" / "materials" / "material.ini"
    summary = parse_materials(source_materials)
    document = material_document_from_summary(summary)
    assert document.rows, "material document has no rows"
    text = generate_materials_ini_text(document)
    assert "Generated by G4UniversalSim GUI" in text

    with tempfile.TemporaryDirectory() as tmp:
        generated = Path(tmp) / "generated_material.ini"
        generated.write_text(text, encoding="utf-8")
        reparsed = parse_materials(generated)
        assert reparsed.materials, "generated materials did not parse"

    with tempfile.TemporaryDirectory() as tmp:
        invalid_source = Path(tmp) / "invalid_source.ini"
        invalid_source.write_text(
            "[Alias]\nmaterial = G4_AIR\nExtraField = must-not-disappear\n",
            encoding="utf-8",
        )
        invalid_summary = parse_materials(invalid_source)
        assert invalid_summary.errors
        source_error = invalid_summary.errors[0]
        assert "line 3, section 'Alias', key 'ExtraField', value 'must-not-disappear'" in source_error
        invalid_document = material_document_from_summary(invalid_summary)
        assert invalid_document.source_errors == [source_error]
        assert source_error in invalid_document.errors
        validate_material_document(invalid_document)
        validate_material_document(invalid_document)
        assert invalid_document.source_errors == [source_error]
        assert invalid_document.errors.count(source_error) == 1
        invalid_document.rows[0].notes = "edited after loading invalid source"
        invalid_document.is_dirty = True
        validate_material_document(invalid_document)
        assert source_error in invalid_document.errors
        try:
            generate_materials_ini_text(invalid_document)
        except ValueError as exc:
            assert source_error in str(exc)
        else:
            raise AssertionError("Invalid source schema was silently sanitized in generated preview")

    invalid = MaterialDocument(rows=[
        MaterialRow(name="BadMass", mode="mass_fraction", density="1.0 g/cm3", components_text="G4_Si:0.2\nG4_O:0.2"),
        MaterialRow(name="BadMass", mode="mass_fraction", density="1.0 g/cm3", components_text="G4_Si:1.0"),
        MaterialRow(name="BadAtom", mode="atom_count", density="1.0 g/cm3", components_text="G4_H:1.5"),
        MaterialRow(name="MissingDensity", mode="mass_fraction", density="", components_text="G4_Si:1.0"),
        MaterialRow(name="VF", mode="volume_fraction", density="auto", components_text="G4_SILICON_DIOXIDE:0.5\nG4_POLYETHYLENE:0.5"),
    ])
    validate_material_document(invalid)
    errors = "\n".join(invalid.errors)
    assert "duplicate material name" in errors
    assert "must sum to 1.0" in errors
    assert "atom_count value must be an integer" in errors
    assert "density is required" in errors
    assert not any("VF:" in error for error in invalid.errors), "volume_fraction density=auto should pass"

    refs = MaterialDocument(rows=[MaterialRow(name="CustomA", mode="mass_fraction", density="1.0 g/cm3", components_text="G4_Si:1.0")])
    validate_material_document(refs, geometry_material_refs={"CustomA"})
    assert not refs.errors
    refs.rows.clear()
    validate_material_document(refs, geometry_material_refs={"CustomA"})
    assert any("CustomA" in error for error in refs.errors)

    with tempfile.TemporaryDirectory() as tmp:
        tmp_path = Path(tmp)
        exe = tmp_path / "G4UniversalSim.exe"
        exe.write_text("fake", encoding="utf-8")
        edited = MaterialDocument(rows=[MaterialRow(name="CustomA", mode="mass_fraction", density="1.0 g/cm3", components_text="G4_Si:1.0")])
        edited.is_dirty = True
        package, report = create_run_package(
            project=G4USimProject(projectName="smoke"),
            paths=PathSettings(
                executable=str(exe),
                workspace_root=str(root),
                runs_root=str(tmp_path / "runs"),
                materials_config=str(source_materials),
                geometry_config=str(root / "config" / "geometry" / "simple_box.ini"),
            ),
            run=RunSettings(run_name="smoke", threads=1, beam_on=0),
            geometry=GeometrySettings(template="simple_box", config_path=str(root / "config" / "geometry" / "simple_box.ini")),
            source=SourceSettings(),
            physics=PhysicsSettings(),
            scoring=ScoringSettings(),
            material_document=edited,
        )
        package_materials = Path(package.materials_ini_path).read_text(encoding="utf-8")
        assert "[material.CustomA]" in package_materials
        assert "generated by Materials Editor" in report
        assert source_materials.read_text(encoding="utf-8") == (root / "config" / "materials" / "material.ini").read_text(encoding="utf-8")

        invalid_source = tmp_path / "invalid-package-materials.ini"
        invalid_source.write_text(
            "[Alias]\nmaterial = G4_AIR\nExtraField = must-not-disappear\n",
            encoding="utf-8",
        )
        invalid_document = material_document_from_summary(parse_materials(invalid_source))
        invalid_document.rows[0].notes = "edited"
        invalid_document.is_dirty = True
        try:
            create_run_package(
                project=G4USimProject(projectName="invalid-material-source"),
                paths=PathSettings(
                    executable=str(exe),
                    workspace_root=str(root),
                    runs_root=str(tmp_path / "invalid-runs"),
                    materials_config=str(invalid_source),
                    geometry_config=str(root / "config" / "geometry" / "simple_box.ini"),
                ),
                run=RunSettings(run_name="invalid-material-source", threads=1, beam_on=0),
                geometry=GeometrySettings(template="simple_box", config_path=str(root / "config" / "geometry" / "simple_box.ini")),
                source=SourceSettings(),
                physics=PhysicsSettings(),
                scoring=ScoringSettings(),
                material_document=invalid_document,
            )
        except ValueError as exc:
            assert "ExtraField" in str(exc)
            assert "must-not-disappear" in str(exc)
        else:
            raise AssertionError("Run package generation accepted a source material schema error")
        assert not (tmp_path / "invalid-runs").exists(), "Invalid package should fail before allocation"

    duplicate_row(document, 0)
    assert any(row.name.endswith("_copy") for row in document.rows)
    add_default_row(document, "volume_fraction")
    assert any(row.mode == "volume_fraction" for row in document.rows)
    check_backend_rules(root)
    print("smoke_materials_editor: ok")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
