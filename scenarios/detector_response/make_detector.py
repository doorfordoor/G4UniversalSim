"""Generates a detector response scenario (roadmap Phase B4).

Two detector kinds, both scored as the per-event energy deposit in the sensitive
volume (event_edep_tN.csv = pulse height before resolution):

  gamma    cylindrical crystal (--crystal: NaI, CsI, BGO, LaBr3, HPGe, plastic, CZT)
           of radius --radius and length --length, optional Al housing, irradiated by
           an isotropic point source on the axis at --distance from the front face.
           The source emits into the cone that contains the housing (min/max theta),
           so absolute efficiencies are scaled by the cone fraction (1 - cos a) / 2.
  silicon  Si pad of thickness --thickness and side --size, parallel beam of
           charged particles at normal incidence (energy deposit spectrum, MPV).

    python scenarios/detector_response/make_detector.py --out work/nai --kind gamma \\
        --crystal NaI --radius 38.1mm --length 76.2mm --energy 0.662 --events 20000
    G4UniversalSim.exe --config work/nai/main.ini    (started from work/nai)
    python scenarios/detector_response/analyze_detector.py work/nai/output --fwhm 0,0.04,0
"""

from __future__ import annotations

import argparse
import json
import math
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "shielding_coating"))
from make_scenario import length_mm  # noqa: E402

CRYSTALS = {  # name: (Geant4 material, custom definition or None)
    "NaI": ("G4_SODIUM_IODIDE", None),
    "CsI": ("G4_CESIUM_IODIDE", None),
    "BGO": ("G4_BGO", None),
    "HPGe": ("G4_Ge", None),
    "plastic": ("G4_PLASTIC_SC_VINYLTOLUENE", None),
    "LaBr3": ("LaBr3", (5.08, "G4_La:1, G4_Br:3")),
    "CZT": ("CZT", (5.78, "G4_Cd:9, G4_Zn:1, G4_Te:10")),
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True)
    parser.add_argument("--run-from", default="", help="directory the backend is started from (default: --out)")
    parser.add_argument("--kind", default="gamma", choices=["gamma", "silicon"])
    parser.add_argument("--crystal", default="NaI", choices=sorted(CRYSTALS))
    parser.add_argument("--radius", default="38.1mm")
    parser.add_argument("--length", default="76.2mm")
    parser.add_argument("--housing", default="0.5mm", help="Al housing thickness around the crystal, or 0")
    parser.add_argument("--distance", default="100mm", help="source to front face of the housing")
    parser.add_argument("--thickness", default="300um", help="silicon pad thickness")
    parser.add_argument("--size", default="10mm", help="silicon pad side")
    parser.add_argument("--particle", default="", help="default gamma (gamma kind) / proton (silicon kind)")
    parser.add_argument("--energy", type=float, required=True, help="MeV")
    parser.add_argument("--physics", default="FTFP_BERT")
    parser.add_argument("--em", default="option4")
    parser.add_argument("--cut", default="10 um", help="production cut in the detector")
    parser.add_argument("--events", type=int, default=10000)
    parser.add_argument("--threads", type=int, default=4)
    parser.add_argument("--seed", type=int, default=4242)
    args = parser.parse_args()

    out = Path(args.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    base = Path(args.run_from).resolve() if args.run_from else out
    prefix = Path(os.path.relpath(out, base)).as_posix()

    def rel(name: str) -> str:
        return name if prefix == "." else f"{prefix}/{name}"

    particle = args.particle or ("gamma" if args.kind == "gamma" else "proton")
    materials = ["# generated by make_detector.py", "[nist]"]
    geo = ["# generated by make_detector.py", "[world]", "shape = box", "size = 2 m, 2 m, 2 m",
           "material = G4_Galactic"]
    meta = {"kind": args.kind, "particle": particle, "energy_MeV": args.energy, "events": args.events}
    if args.kind == "gamma":
        material, custom = CRYSTALS[args.crystal]
        nist = {"G4_Galactic", "G4_Al"} | ({material} if custom is None else set())
        materials.append("materials = " + ", ".join(sorted(nist)))
        if custom:
            materials += ["", f"[material.{material}]", "mode = atom_count", f"density = {custom[0]} g/cm3",
                          f"components = {custom[1]}", "state = solid"]
        radius, length = length_mm(args.radius), length_mm(args.length)
        housing = 0.0 if args.housing in ("0", "none") else length_mm(args.housing)
        distance = length_mm(args.distance)
        outer_r, outer_l = radius + housing, length + 2 * housing
        z_centre = distance + outer_l / 2
        if housing:
            geo += ["", "[volume.Housing]", "parent = world", "shape = tubs",
                    f"parameters = 0 mm, {outer_r:g} mm, {outer_l / 2:g} mm, 0 deg, 360 deg", "material = G4_Al",
                    f"position = 0 mm, 0 mm, {z_centre:g} mm"]
        geo += ["", "[volume.Crystal]", f"parent = {'Housing' if housing else 'world'}", "shape = tubs",
                f"parameters = 0 mm, {radius:g} mm, {length / 2:g} mm, 0 deg, 360 deg", f"material = {material}",
                f"position = 0 mm, 0 mm, {0 if housing else z_centre:g} mm", "sensitive = true", "region = Detector"]
        # cone from the source that contains the whole housing (front and back rims)
        cone = max(math.atan2(outer_r, distance), math.atan2(outer_r, distance + outer_l)) + math.radians(1)
        cone = min(cone, math.pi / 2)
        fraction = (1 - math.cos(cone)) / 2
        source = ["[source]", f"particle = {particle}", f"energy = {args.energy} MeV", "position_type = point",
                  "position = 0 mm, 0 mm, 0 mm", "angular = isotropic", "direction = 0, 0, 1",
                  f"max_theta = {math.degrees(cone):.6g} deg"]
        meta.update(crystal=args.crystal, material=material, radius_mm=radius, length_mm=length,
                    housing_mm=housing, distance_mm=distance, cone_half_angle_deg=math.degrees(cone),
                    cone_fraction_of_4pi=fraction)
    else:
        materials.append("materials = G4_Galactic, G4_Si")
        thickness, size = length_mm(args.thickness), length_mm(args.size)
        geo += ["", "[volume.Pad]", "parent = world", "shape = box",
                f"size = {size:g} mm, {size:g} mm, {thickness:.6g} mm", "material = G4_Si",
                f"position = 0 mm, 0 mm, {thickness / 2:.6g} mm", "sensitive = true", "region = Detector"]
        source = ["[source]", f"particle = {particle}", f"energy = {args.energy} MeV", "position_type = plane",
                  "shape = square", f"halfx = {size / 4:g} mm", "center = 0 mm, 0 mm, -1 mm",
                  "direction = 0, 0, 1"]
        meta.update(material="G4_Si", thickness_mm=thickness, size_mm=size)
    (out / "materials.ini").write_text("\n".join(materials) + "\n", encoding="utf-8")
    (out / "geometry.ini").write_text("\n".join(geo) + "\n", encoding="utf-8")

    physics = ["[physics]", f"reference = {args.physics}", f"em = {args.em}", "default_cut = 0.7 mm", "",
               "[physics.region.Detector]"] + [f"{p} = {args.cut}" for p in ("gamma", "e-", "e+")]
    scoring = ["[scoring]", "enabled = true", "hits = false", "event_edep = true", "edep = false"]
    settings = {k: v for k, v in vars(args).items() if k not in ("out", "run_from")}
    main_ini = ["# generated by make_detector.py: " + " ".join(f"{k}={v}" for k, v in settings.items()),
                "[run]", f"threads = {args.threads}", f"seed = {args.seed}", f"macro = {rel('run.mac')}", "",
                "[output]", f"dir = {rel('output')}", "format = csv", "", "[materials]",
                f"file = {rel('materials.ini')}", "", "[geometry]", "template = hierarchical",
                f"config = {rel('geometry.ini')}", "", *physics, "", *scoring, "", *source, ""]
    (out / "main.ini").write_text("\n".join(main_ini), encoding="utf-8")
    (out / "run.mac").write_text(f"/run/initialize\n/run/beamOn {args.events}\n", encoding="utf-8")
    (out / "scenario.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    print(f"detector scenario written to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
