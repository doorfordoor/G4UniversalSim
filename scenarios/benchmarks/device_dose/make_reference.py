"""Builds reference.csv of the device_dose benchmark.

Geometry of every case: a sensitive Si slab (thickness t) embedded in silicon with a
build-up layer b in front and the same backing behind it, irradiated at normal
incidence by a broad beam (fluence Phi = N / A at the slab).

  tid  dose per unit fluence of protons, D / Phi = S_el(E_mid) [MeV cm2/g] x
       1.602176634e-10 Gy g / MeV, with S_el the PSTAR electronic stopping power of
       Si (../shielding_range/nist/PSTAR_Si.txt) at the mean energy in the slab,
       E_mid = R^-1(R(E) - rho (b + t/2)) from the PSTAR CSDA range. The build-up and
       backing are thicker than the range of the fastest delta electrons, so the slab
       is in delta-electron equilibrium and its dose equals the collision kerma.
  ddd  displacement damage dose per unit fluence, DDD / Phi = NIEL(E_mid) of the
       SR-NIEL silicon table (../../semiconductor/niel/si_<particle>.csv, log-log
       interpolation as in the scorer). This checks the track-length fluence and the
       fold with the reference table; it does not validate the NIEL data itself.

    python scenarios/benchmarks/device_dose/make_reference.py
"""

from __future__ import annotations

import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
PSTAR_SI = HERE.parent / "shielding_range" / "nist" / "PSTAR_Si.txt"
NIEL = HERE.parents[1] / "semiconductor" / "niel"
RHO_SI = 2.33
GY_PER_MEV_G = 1.602176634e-10

#        kind, particle, energy MeV, build-up mm, slab mm
CASES = [("tid", "proton", 10.0, 0.05, 0.02), ("tid", "proton", 50.0, 0.3, 0.1),
         ("tid", "proton", 100.0, 0.6, 0.1), ("tid", "proton", 200.0, 1.5, 0.2),
         ("ddd", "proton", 10.0, 0.05, 0.02), ("ddd", "proton", 100.0, 0.6, 0.1),
         ("ddd", "neutron", 14.0, 0.6, 0.1)]


def loglog(x: float, xs: list[float], ys: list[float]) -> float:
    for i in range(len(xs) - 1):
        if xs[i] <= x <= xs[i + 1]:
            if ys[i] > 0 and ys[i + 1] > 0:
                t = math.log(x / xs[i]) / math.log(xs[i + 1] / xs[i])
                return math.exp(math.log(ys[i]) + t * (math.log(ys[i + 1]) - math.log(ys[i])))
            return ys[i] + (x - xs[i]) / (xs[i + 1] - xs[i]) * (ys[i + 1] - ys[i])
    raise ValueError(f"{x} outside the table")


def pstar() -> list[list[float]]:
    rows = []
    for line in PSTAR_SI.read_text(encoding="ascii").splitlines():
        try:
            values = [float(p) for p in line.split()]
        except ValueError:
            continue
        if len(values) == 7:
            rows.append(values)
    return rows


def niel(particle: str) -> tuple[list[float], list[float]]:
    xs, ys = [], []
    for line in (NIEL / f"si_{particle}.csv").read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or line.startswith("energy"):
            continue
        e, v = line.split(",")
        xs.append(float(e))
        ys.append(float(v))
    return xs, ys


def main() -> None:
    table = pstar()
    energies, se, csda = [r[0] for r in table], [r[1] for r in table], [r[4] for r in table]
    lines = ["# device_dose benchmark references, generated by make_reference.py. tid: PSTAR Si",
             "# electronic stopping power x 1.602176634e-10 at E_mid; ddd: SR-NIEL Si NIEL at E_mid.",
             "kind,particle,energy_MeV,buildup_mm,slab_mm,mean_energy_MeV,reference,unit,source"]
    for kind, particle, energy, buildup, slab in CASES:
        if particle == "proton":
            depth = RHO_SI * (buildup + slab / 2) / 10.0
            mid = loglog(loglog(energy, energies, csda) - depth, csda, energies)
        else:
            mid = energy   # no continuous energy loss
        if kind == "tid":
            value, unit, source = loglog(mid, energies, se) * GY_PER_MEV_G, "Gy cm2", "PSTAR Si STOP(e)"
        else:
            value, unit, source = loglog(mid, *niel(particle)), "MeV cm2/g", f"SR-NIEL si_{particle}.csv"
        lines.append(f"{kind},{particle},{energy:g},{buildup:g},{slab:g},{mid:.5g},{value:.6g},{unit},{source}")
    (HERE / "reference.csv").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
