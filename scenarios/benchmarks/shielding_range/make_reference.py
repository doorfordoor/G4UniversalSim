"""Builds reference.csv of the shielding_range benchmark from the NIST tables in nist/.

nist/PSTAR_*.txt and nist/ESTAR_*.txt are the default text tables of the NIST
PSTAR / ESTAR programs (https://physics.nist.gov/PhysRefData/Star/Text/) for
aluminium and silicon, saved unchanged. Two kinds of reference values:

  csda_range        CSDA range at a tabulated energy (column RANGE(c) / CSDA Range)
  residual_energy   mean energy of protons after a slab of areal density t, from the
                    CSDA range: E_out = R^-1(R(E_in) - t), log-log interpolation between
                    tabulated points (path length = slab thickness, adequate for slabs
                    much thinner than the range). The same inversion with the projected
                    range Rp (which includes the PSTAR detour factor of the whole
                    remaining track) is listed as projected_range_energy_MeV for
                    information; it is a lower bound because a straight-ahead proton
                    in a thin slab has not yet accumulated that detour.

    python scenarios/benchmarks/shielding_range/make_reference.py
"""

from __future__ import annotations

import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
# Geant4 NIST material densities (g/cm3) used to convert slab thickness to g/cm2.
DENSITY = {"G4_Al": 2.699, "G4_Si": 2.33}
FILE_TAG = {"G4_Al": "Al", "G4_Si": "Si"}

CSDA_CASES = [("proton", "G4_Al", 10.0), ("proton", "G4_Al", 100.0), ("proton", "G4_Si", 10.0),
              ("proton", "G4_Si", 100.0), ("e-", "G4_Al", 1.0), ("e-", "G4_Al", 5.0), ("e-", "G4_Si", 1.0)]
RESIDUAL_CASES = [("G4_Al", 20.0, 1.0), ("G4_Al", 50.0, 5.0), ("G4_Al", 100.0, 20.0), ("G4_Si", 30.0, 2.0)]


def numbers(path: Path) -> list[list[float]]:
    rows = []
    for line in path.read_text(encoding="ascii").splitlines():
        parts = line.split()
        try:
            values = [float(p) for p in parts]
        except ValueError:
            continue
        if len(values) >= 6:
            rows.append(values)
    return rows


def pstar(material: str) -> list[list[float]]:     # T, Se, Sn, St, Rcsda, Rp, detour
    return numbers(HERE / "nist" / f"PSTAR_{FILE_TAG[material]}.txt")


def estar(material: str) -> list[list[float]]:     # T, Scol, Srad, Stot, Rcsda, yield, delta
    return numbers(HERE / "nist" / f"ESTAR_{FILE_TAG[material]}.txt")


def loglog(x: float, xs: list[float], ys: list[float]) -> float:
    for i in range(len(xs) - 1):
        if xs[i] <= x <= xs[i + 1]:
            t = math.log(x / xs[i]) / math.log(xs[i + 1] / xs[i])
            return math.exp(math.log(ys[i]) + t * (math.log(ys[i + 1]) - math.log(ys[i])))
    raise ValueError(f"{x} outside the table")


def main() -> None:
    lines = ["# Shielding range benchmark references, generated by make_reference.py from the NIST",
             "# PSTAR/ESTAR tables in nist/ (https://physics.nist.gov/PhysRefData/Star/Text/).",
             "# csda_range: tabulated CSDA range (g/cm2). residual_energy: E_out = R^-1(R(E_in) - t)",
             "# with R the CSDA range, log-log interpolation, t = density x thickness; the projected",
             "# range inversion is given for information only.",
             "kind,particle,material,density_g_cm3,energy_MeV,thickness_mm,reference,unit,source,"
             "projected_range_energy_MeV"]
    for particle, material, energy in CSDA_CASES:
        table = pstar(material) if particle == "proton" else estar(material)
        row = next(r for r in table if abs(r[0] - energy) < 1e-9 * energy)
        source = f"{'PSTAR' if particle == 'proton' else 'ESTAR'} {FILE_TAG[material]}"
        lines.append(f"csda_range,{particle},{material},{DENSITY[material]},{energy:g},,{row[4]:.4g},g/cm2,{source},")
    for material, energy, thickness in RESIDUAL_CASES:
        table = pstar(material)
        energies = [r[0] for r in table]
        areal = DENSITY[material] * thickness / 10.0

        def residual(column: int) -> float:
            ranges = [r[column] for r in table]
            return loglog(loglog(energy, energies, ranges) - areal, ranges, energies)

        lines.append(f"residual_energy,proton,{material},{DENSITY[material]},{energy:g},{thickness:g},"
                     f"{residual(4):.4f},MeV,PSTAR {FILE_TAG[material]} CSDA range,{residual(5):.4f}")
    (HERE / "reference.csv").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
