"""Generates a semiconductor device dose / displacement damage scenario (roadmap Phase B3).

A silicon die under an optional package lid / shield, irradiated at normal incidence
by a square plane source that covers the die (mono-energetic or an integral-flux
spectrum, protons, electrons, neutrons or protons + electrons):

  source | lid (--lid, optional) | gap | BEOL layers (--beol) | GateOxide (SiO2) |
  Active (Si) | Substrate (Si, --slices replica slices for depth profiles)

GateOxide, Active and every substrate slice are sensitive: dose (TID in Gy of the
layer material), track-length fluence and displacement damage dose (DDD) folded
with the SR-NIEL silicon tables in niel/ (proton, e-, neutron; --niel overrides).
Displacement damage is only meaningful in the silicon layers (the tables are for
Si); the oxide's DDD is reported but uses the Si tables.

    python scenarios/semiconductor/make_device.py --out work/device --particle proton --energy 50
    G4UniversalSim.exe --config work/device/main.ini      (started from work/device)
    python scenarios/semiconductor/analyze_device.py work/device/output
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "shielding_coating"))
from make_scenario import CUSTOM, ENVIRONMENT, density, length_mm, spectrum_from_integral_flux  # noqa: E402

NIEL_DEFAULT = {"proton": HERE / "niel" / "si_proton.csv", "e-": HERE / "niel" / "si_electron.csv",
                "neutron": HERE / "niel" / "si_neutron.csv"}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True)
    parser.add_argument("--run-from", default="", help="directory the backend is started from (default: --out)")
    parser.add_argument("--lid", default="G4_Al:1mm", help="material:thickness of the lid/shield, or 'none'")
    parser.add_argument("--beol", default="G4_SILICON_DIOXIDE:3um,G4_Al:1um,G4_SILICON_DIOXIDE:2um",
                        help="back-end-of-line layers above the gate oxide, beam side first, or 'none'")
    parser.add_argument("--oxide", default="100nm", help="gate oxide thickness")
    parser.add_argument("--active", default="10um", help="active silicon thickness")
    parser.add_argument("--substrate", default="300um")
    parser.add_argument("--slices", type=int, default=10, help="substrate depth slices")
    parser.add_argument("--die", default="5mm", help="lateral die size")
    parser.add_argument("--lid-size", default="20mm", help="lateral lid size")
    parser.add_argument("--particle", default="proton", choices=["proton", "e-", "neutron", "mixed"])
    parser.add_argument("--energy", type=float, default=0.0, help="mono-energetic MeV (default: spectrum)")
    parser.add_argument("--proton-spectrum", default=str(ENVIRONMENT / "proton_integral_flux.txt"))
    parser.add_argument("--electron-spectrum", default=str(ENVIRONMENT / "electron_integral_flux.txt"))
    parser.add_argument("--niel", action="append", default=[], metavar="PARTICLE=TABLE.csv",
                        help="replace/add a NIEL table (default: SR-NIEL Si tables for proton, e-, neutron)")
    parser.add_argument("--physics", default="QGSP_BIC_HP")
    parser.add_argument("--em", default="option4")
    parser.add_argument("--device-cut", default="10 um")
    parser.add_argument("--events", type=int, default=2000)
    parser.add_argument("--threads", type=int, default=4)
    parser.add_argument("--seed", type=int, default=2026)
    args = parser.parse_args()

    out = Path(args.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    base = Path(args.run_from).resolve() if args.run_from else out
    prefix = Path(os.path.relpath(out, base)).as_posix()

    def rel(name: str) -> str:
        return name if prefix == "." else f"{prefix}/{name}"

    def layer_list(text: str) -> list[tuple[str, float]]:
        if text.strip().lower() == "none":
            return []
        result = []
        for item in text.split(","):
            material, _, thickness = item.strip().partition(":")
            density(material)
            result.append((material, length_mm(thickness)))
        return result

    lid = layer_list(args.lid)
    if len(lid) > 1:
        raise SystemExit("--lid takes one material:thickness")
    beol = layer_list(args.beol)
    if args.slices < 1:
        raise SystemExit("--slices must be >= 1")
    die_half = length_mm(args.die) / 2
    lid_half = length_mm(args.lid_size) / 2

    used = {m for m, _ in lid + beol}
    lines = ["# generated by make_device.py", "[nist]",
             "materials = " + ", ".join(sorted({"G4_Galactic", "G4_Si", "G4_SILICON_DIOXIDE"} |
                                               {m for m in used if m.startswith("G4_")}))]
    for name in sorted(m for m in used if m in CUSTOM):
        rho, components = CUSTOM[name]
        lines += ["", f"[material.{name}]", "mode = atom_count", f"density = {rho} g/cm3",
                  f"components = {components}", "state = solid"]
    (out / "materials.ini").write_text("\n".join(lines) + "\n", encoding="utf-8")

    geo = ["# generated by make_device.py", "[world]", "shape = box", "size = 20 cm, 20 cm, 20 cm",
           "material = G4_Galactic"]

    def box(name, material, half, thickness, z_centre, parent="world", extra=()):
        geo.extend(["", f"[volume.{name}]", f"parent = {parent}", "shape = box",
                    f"size = {2 * half:g} mm, {2 * half:g} mm, {thickness:.6g} mm", f"material = {material}",
                    f"position = 0 mm, 0 mm, {z_centre:.6g} mm", *extra])

    z = 0.0
    if lid:
        material, thickness = lid[0]
        box("Lid", material, lid_half, thickness, z + thickness / 2)
        z += thickness
    z += 1.0   # gap between lid and die
    layers = []
    for index, (material, thickness) in enumerate(beol):
        name = f"Beol{index}_{material.replace('G4_', '')}"
        box(name, material, die_half, thickness, z + thickness / 2, extra=["region = Device"])
        z += thickness
    oxide, active, substrate = length_mm(args.oxide), length_mm(args.active), length_mm(args.substrate)
    for name, material, thickness in (("GateOxide", "G4_SILICON_DIOXIDE", oxide), ("Active", "G4_Si", active)):
        box(name, material, die_half, thickness, z + thickness / 2, extra=["sensitive = true", "region = Device"])
        layers.append({"name": name, "material": material, "depth_mm": z, "thickness_mm": thickness})
        z += thickness
    box("Substrate", "G4_Si", die_half, substrate, z + substrate / 2, extra=["region = Device"])
    width = substrate / args.slices
    geo.extend(["", "[volume.Slice]", "parent = Substrate", "shape = box",
                f"size = {2 * die_half:g} mm, {2 * die_half:g} mm, {width:.6g} mm", "material = G4_Si",
                "placement = replica", "replica_axis = z", f"replica_count = {args.slices}",
                f"replica_width = {width:.6g} mm", "sensitive = true"])
    slices = [{"copy": i, "depth_mm": z + i * width, "thickness_mm": width} for i in range(args.slices)]
    (out / "geometry.ini").write_text("\n".join(geo) + "\n", encoding="utf-8")

    def source_block(header, particle, intensity=None):
        block = [header, f"particle = {particle}"]
        if intensity is not None:
            block.append(f"intensity = {intensity:.6g}")
        sampled = None
        if args.energy > 0:
            block.append(f"energy = {args.energy} MeV")
        else:
            if particle == "neutron":
                raise SystemExit("neutrons need --energy (no neutron spectrum file)")
            spectrum = Path(args.proton_spectrum if particle == "proton" else args.electron_spectrum)
            target = out / f"spectrum_{'proton' if particle == 'proton' else 'electron'}.csv"
            sampled = spectrum_from_integral_flux(spectrum, target)
            block += ["energy_type = histogram", f"spectrum_file = {target.name}"]
        block += ["position_type = plane", "shape = square", f"halfx = {die_half:g} mm",
                  "center = 0 mm, 0 mm, -1 mm", "direction = 0, 0, 1"]
        return block, sampled

    if args.particle == "mixed":
        if args.energy > 0:
            raise SystemExit("--particle mixed needs the spectra (no --energy)")
        flux = {}
        for p, s in (("proton", args.proton_spectrum), ("e-", args.electron_spectrum)):
            flux[p] = spectrum_from_integral_flux(Path(s), out / "tmp.csv")[0]
        (out / "tmp.csv").unlink()
        proton_block, sampled_p = source_block("[source.protons]", "proton", flux["proton"])
        electron_block, sampled_e = source_block("[source.electrons]", "e-", flux["e-"])
        source = ["[source]", "verbose = 0", ""] + proton_block + [""] + electron_block
        sampled = {"proton": sampled_p, "e-": sampled_e}
    else:
        source, value = source_block("[source]", args.particle)
        sampled = {args.particle: value}

    def niel_path(table: Path) -> str:
        # The backend resolves NIEL tables next to main.ini; keep the scenario relocatable.
        try:
            return Path(os.path.relpath(table.resolve(), out)).as_posix()
        except ValueError:   # different drive
            return table.resolve().as_posix()

    tables = {p: Path(t) for p, t in NIEL_DEFAULT.items()}
    for item in args.niel:
        particle, _, table = item.partition("=")
        if not particle or not table:
            raise SystemExit(f"--niel needs PARTICLE=TABLE.csv, got '{item}'")
        tables[particle.strip()] = Path(table)
    scoring = ["[scoring]", "enabled = true", "hits = false", "event_edep = false", "edep = false",
               "dose = true", "fluence = true", "displacement = true", "auto_create_default_scorers = true", "",
               "[scoring.displacement]"] + [f"{p} = {niel_path(t)}" for p, t in sorted(tables.items())]
    physics = ["[physics]", f"reference = {args.physics}", f"em = {args.em}", "default_cut = 0.1 mm", "",
               "[physics.region.Device]"] + [f"{p} = {args.device_cut}" for p in ("gamma", "e-", "e+")]
    settings = {k: v for k, v in vars(args).items() if k not in ("out", "niel", "run_from")}
    for key in ("proton_spectrum", "electron_spectrum"):
        settings[key] = Path(settings[key]).name
    main_ini = ["# generated by make_device.py: " + " ".join(f"{k}={v}" for k, v in settings.items()),
                "[run]", f"threads = {args.threads}", f"seed = {args.seed}", f"macro = {rel('run.mac')}", "",
                "[output]", f"dir = {rel('output')}", "format = csv", "", "[materials]",
                f"file = {rel('materials.ini')}", "", "[geometry]", "template = hierarchical",
                f"config = {rel('geometry.ini')}", "", *physics, "", *scoring, "", *source, ""]
    (out / "main.ini").write_text("\n".join(main_ini), encoding="utf-8")
    (out / "run.mac").write_text(f"/run/initialize\n/run/beamOn {args.events}\n", encoding="utf-8")
    meta = {"particle": args.particle, "energy_MeV": args.energy or None, "events": args.events,
            "source_area_cm2": (2 * die_half / 10) ** 2,
            "sampled_integral_flux_cm2_s": {k: (v[0] if v else None) for k, v in sampled.items()},
            "unsampled_flux_above_last_energy_cm2_s": {k: (v[1] if v else None) for k, v in sampled.items()},
            "lid": [{"material": m, "thickness_mm": t} for m, t in lid],
            "beol": [{"material": m, "thickness_mm": t} for m, t in beol],
            "layers": layers, "slices": slices,
            "niel_tables": {p: niel_path(t) for p, t in sorted(tables.items())}}
    (out / "scenario.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    print(f"device scenario written to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
